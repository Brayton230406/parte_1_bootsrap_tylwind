import { Router } from 'express';
import { rateLimit } from 'express-rate-limit';
import * as auth from '../controllers/auth.controller.js';
import * as products from '../controllers/product.controller.js';
import * as orders from '../controllers/order.controller.js';
import * as operations from '../controllers/operations.controller.js';
import * as admin from '../controllers/admin.controller.js';
import { requireAuth, requireRole } from '../middleware/auth.js';
const api=Router();
const loginLimit=rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:'draft-8',legacyHeaders:false,message:{status:'error',error:{message:'Demasiados intentos. Intenta más tarde.'}}});
api.get('/productos',products.list);
api.get('/productos/:id',products.get);
api.post('/auth/registro',loginLimit,auth.register);
api.post('/auth/login',loginLimit,auth.login);
api.put('/auth/contrasena',loginLimit,requireAuth,auth.changePassword);
api.get('/auth/me',requireAuth,auth.me);
api.post('/auth/logout',requireAuth,auth.logout);
api.get('/carrito',requireAuth,requireRole('cliente'),orders.getCart);
api.put('/carrito',requireAuth,requireRole('cliente'),orders.putCart);
api.get('/pedidos',requireAuth,requireRole('cliente'),orders.list);
api.post('/pedidos',requireAuth,requireRole('cliente'),orders.create);
api.get('/pedidos/:id',requireAuth,requireRole('cliente'),orders.detail);
api.post('/pedidos/:id/cancelacion',requireAuth,requireRole('cliente'),orders.cancel);
api.use('/admin',requireAuth,requireRole('administrador'));
api.post('/admin/operaciones/ubicacion',operations.createStockLocation);
api.post('/admin/operaciones/conteo',operations.countStock);
api.post('/admin/operaciones/facturar',operations.invoice);
api.post('/admin/operaciones/pagar',operations.payment);
api.post('/admin/operaciones/recibir',operations.receive);
api.post('/admin/operaciones/despachar',operations.dispatch);
api.post('/admin/operaciones/entregar',operations.delivered);
api.get('/admin/esquema',admin.schema);
api.get('/admin/:table',admin.list);
api.post('/admin/:table',admin.create);
api.patch('/admin/:table',admin.update);
api.delete('/admin/:table',admin.remove);
export default api;
