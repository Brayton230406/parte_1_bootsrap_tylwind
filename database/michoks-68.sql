    CONSTRAINT pk_repartidor PRIMARY KEY (id_repartidor),

    CONSTRAINT fk_repartidor_transportista
        FOREIGN KEY (id_transportista)
        REFERENCES transportista (id_transportista)
);


CREATE TABLE vehiculo (
    id_vehiculo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_transportista BIGINT NOT NULL,
    placa VARCHAR(20) NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    capacidad NUMERIC(14,3),
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_vehiculo PRIMARY KEY (id_vehiculo),
    CONSTRAINT uq_vehiculo_placa UNIQUE (placa),

    CONSTRAINT fk_vehiculo_transportista
        FOREIGN KEY (id_transportista)
        REFERENCES transportista (id_transportista),

    CONSTRAINT ck_vehiculo_placa CHECK (btrim(placa) <> ''),
    CONSTRAINT ck_vehiculo_capacidad CHECK (capacidad > 0)
);


CREATE TABLE delivery (
    id_delivery BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_envio BIGINT NOT NULL,
    id_direccion BIGINT NOT NULL,
    id_zona_delivery BIGINT NOT NULL,
    id_tarifa_delivery BIGINT NOT NULL,

    direccion_entrega_snapshot VARCHAR(300) NOT NULL,
    ciudad_snapshot VARCHAR(100) NOT NULL,
    referencia VARCHAR(300),

    latitud NUMERIC(9,6),
    longitud NUMERIC(9,6),

    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ventana_inicio TIMESTAMPTZ NOT NULL,
    ventana_fin TIMESTAMPTZ NOT NULL,
    costo_acordado NUMERIC(16,2) NOT NULL,

    CONSTRAINT pk_delivery PRIMARY KEY (id_delivery),
    CONSTRAINT uq_delivery_envio UNIQUE (id_envio),

    CONSTRAINT fk_delivery_envio
        FOREIGN KEY (id_envio)
        REFERENCES envio (id_envio),

    CONSTRAINT fk_delivery_direccion
        FOREIGN KEY (id_direccion)
        REFERENCES direccion (id_direccion),

    CONSTRAINT fk_delivery_zona_delivery
        FOREIGN KEY (id_zona_delivery)
        REFERENCES zona_delivery (id_zona_delivery),

    CONSTRAINT fk_delivery_tarifa_delivery
        FOREIGN KEY (id_tarifa_delivery)
        REFERENCES tarifa_delivery (id_tarifa_delivery),

    CONSTRAINT ck_delivery_latitud CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_delivery_longitud CHECK (longitud BETWEEN -180 AND 180),

    CONSTRAINT ck_delivery_coordenadas
        CHECK ((latitud IS NULL) = (longitud IS NULL)),

    CONSTRAINT ck_delivery_ventana CHECK (ventana_fin > ventana_inicio),
    CONSTRAINT ck_delivery_costo CHECK (costo_acordado >= 0),

    CONSTRAINT ck_delivery_snapshot
        CHECK (
            btrim(direccion_entrega_snapshot) <> ''
            AND btrim(ciudad_snapshot) <> ''
        )
);


CREATE TABLE asignacion_delivery (
    id_asignacion_delivery BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_delivery BIGINT NOT NULL,
    id_repartidor BIGINT NOT NULL,
    id_vehiculo BIGINT NOT NULL,
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMPTZ,

    CONSTRAINT pk_asignacion_delivery
        PRIMARY KEY (id_asignacion_delivery),

    CONSTRAINT fk_asignacion_delivery_delivery
        FOREIGN KEY (id_delivery)
        REFERENCES delivery (id_delivery),

    CONSTRAINT fk_asignacion_delivery_repartidor
        FOREIGN KEY (id_repartidor)
        REFERENCES repartidor (id_repartidor),

    CONSTRAINT fk_asignacion_delivery_vehiculo
        FOREIGN KEY (id_vehiculo)
        REFERENCES vehiculo (id_vehiculo),

    CONSTRAINT ck_asignacion_delivery_fechas
        CHECK (
            fecha_fin IS NULL
            OR fecha_fin >= fecha_asignacion
        )
);


CREATE TABLE intento_entrega (
    id_intento_entrega BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_delivery BIGINT NOT NULL,
    id_estado_envio BIGINT NOT NULL,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resultado VARCHAR(20) NOT NULL,
    observacion TEXT,

    CONSTRAINT pk_intento_entrega PRIMARY KEY (id_intento_entrega),

    CONSTRAINT fk_intento_entrega_delivery
        FOREIGN KEY (id_delivery)
        REFERENCES delivery (id_delivery),

    CONSTRAINT fk_intento_entrega_estado_envio
        FOREIGN KEY (id_estado_envio)
        REFERENCES estado_envio (id_estado_envio),

    CONSTRAINT ck_intento_entrega_resultado
        CHECK (
            resultado IN (
                'entregado', 'ausente', 'rechazado',
                'direccion_erronea', 'otro'
            )
        )
);


CREATE TABLE evidencia_entrega (
    id_evidencia_entrega BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_intento_entrega BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    url_archivo TEXT NOT NULL,
    receptor VARCHAR(160),
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_evidencia_entrega PRIMARY KEY (id_evidencia_entrega),

    CONSTRAINT fk_evidencia_entrega_intento_entrega
        FOREIGN KEY (id_intento_entrega)
        REFERENCES intento_entrega (id_intento_entrega),

    CONSTRAINT ck_evidencia_entrega_tipo
        CHECK (tipo IN ('foto', 'firma', 'documento', 'otro')),

    CONSTRAINT ck_evidencia_entrega_url CHECK (btrim(url_archivo) <> '')
);


