    descuento NUMERIC(16,2) NOT NULL DEFAULT 0,
    base_imponible NUMERIC(16,2) NOT NULL,
    impuesto NUMERIC(16,2) NOT NULL DEFAULT 0,
    total_linea NUMERIC(16,2) NOT NULL,

    CONSTRAINT pk_detalle_factura PRIMARY KEY (id_detalle_factura),

    CONSTRAINT fk_detalle_factura_factura
        FOREIGN KEY (id_factura)
        REFERENCES factura (id_factura),

    CONSTRAINT fk_detalle_factura_detalle_pedido
        FOREIGN KEY (id_detalle_pedido)
        REFERENCES detalle_pedido (id_detalle_pedido),

    CONSTRAINT uq_detalle_factura_origen
        UNIQUE (id_factura, id_detalle_pedido),

    CONSTRAINT ck_detalle_factura_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_factura_precio CHECK (precio_unitario >= 0),

    CONSTRAINT ck_detalle_factura_descuento
        CHECK (
            descuento >= 0
            AND descuento <= round(cantidad * precio_unitario, 2)
        ),

    CONSTRAINT ck_detalle_factura_base
        CHECK (
            base_imponible >= 0
            AND base_imponible =
                round(cantidad * precio_unitario, 2) - descuento
        ),

    CONSTRAINT ck_detalle_factura_impuesto CHECK (impuesto >= 0),

    CONSTRAINT ck_detalle_factura_total
        CHECK (
            total_linea >= 0
            AND total_linea = base_imponible + impuesto
        )
);


