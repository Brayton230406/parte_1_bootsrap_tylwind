CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre_usuario VARCHAR(60) NOT NULL,
    nombre VARCHAR(160) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    telefono VARCHAR(30),
    password_hash TEXT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acceso TIMESTAMPTZ,

    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),

    CONSTRAINT ck_usuario_nombre_usuario
        CHECK (nombre_usuario ~ '^[A-Za-z0-9_.-]{3,60}$'),

    CONSTRAINT ck_usuario_nombre
        CHECK (btrim(nombre) <> ''),

    CONSTRAINT ck_usuario_correo
        CHECK (
            correo ~
            '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
        ),

    CONSTRAINT ck_usuario_password_hash
        CHECK (btrim(password_hash) <> '')
);

CREATE UNIQUE INDEX uq_usuario_nombre_normalizado
    ON usuario (lower(nombre_usuario));

CREATE UNIQUE INDEX uq_usuario_correo_normalizado
    ON usuario (lower(btrim(correo)));


