    id_estado_factura BIGINT NOT NULL,
    numero VARCHAR(60) NOT NULL,
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Copia historica de los datos utilizados al emitir.
    tipo_identificacion_snapshot VARCHAR(30) NOT NULL,
    identificacion_snapshot VARCHAR(30) NOT NULL,
    razon_social_snapshot VARCHAR(180) NOT NULL,
    direccion_fiscal_snapshot VARCHAR(300) NOT NULL,
    email_snapshot VARCHAR(254),

    subtotal NUMERIC(16,2) NOT NULL,
    descuento NUMERIC(16,2) NOT NULL DEFAULT 0,
    impuesto NUMERIC(16,2) NOT NULL DEFAULT 0,
    total NUMERIC(16,2) NOT NULL,
    moneda CHAR(3) NOT NULL DEFAULT 'USD',

    CONSTRAINT pk_factura PRIMARY KEY (id_factura),
    CONSTRAINT uq_factura_numero UNIQUE (numero),

    CONSTRAINT fk_factura_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES pedido (id_pedido),

    CONSTRAINT fk_factura_datos_facturacion
        FOREIGN KEY (id_datos_facturacion)
        REFERENCES datos_facturacion (id_datos_facturacion),

    CONSTRAINT fk_factura_estado_factura
        FOREIGN KEY (id_estado_factura)
        REFERENCES estado_factura (id_estado_factura),

    CONSTRAINT ck_factura_numero CHECK (btrim(numero) <> ''),

    CONSTRAINT ck_factura_importes
        CHECK (
            subtotal >= 0
            AND descuento >= 0
            AND descuento <= subtotal
            AND impuesto >= 0
            AND total >= 0
        ),

    CONSTRAINT ck_factura_total
        CHECK (total = subtotal - descuento + impuesto),

    CONSTRAINT ck_factura_moneda CHECK (moneda ~ '^[A-Z]{3}$'),

    CONSTRAINT ck_factura_snapshot
        CHECK (
            btrim(tipo_identificacion_snapshot) <> ''
            AND btrim(identificacion_snapshot) <> ''
            AND btrim(razon_social_snapshot) <> ''
            AND btrim(direccion_fiscal_snapshot) <> ''
        )
);


